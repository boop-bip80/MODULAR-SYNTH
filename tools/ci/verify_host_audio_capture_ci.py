#!/usr/bin/env python3
"""Verify operator-supplied host audio against *this* CI build's plugin binary.

The offline signal analysis lives in verify_host_audio_capture.py. This
additional gate refuses packages with a source mismatch or whose claimed
plugin file is not byte-for-byte the just-built LV2/VST2/VST3 artifact.
Neither check proves that the named DAW generated the submitted WAVs.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import stat
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO))

from tools.ci.verify_host_audio_capture import (  # noqa: E402
    CaptureError,
    MAX_MANIFEST,
    _unique,
    verify,
)


def built_plugin_path(fmt: str, mode: str, bin_dir: Path, lv2_dir: Path) -> Path:
    if fmt not in ("LV2", "VST2", "VST3") or mode not in ("synth", "effect"):
        raise CaptureError("unsupported built plugin format or mode")
    variant = "CardinalSynth" if mode == "synth" else "CardinalFX"
    if fmt == "LV2":
        return lv2_dir / f"{variant}.lv2" / f"{variant}.so"
    if fmt == "VST2":
        return bin_dir / "Cardinal.vst" / f"{variant}.so"
    return bin_dir / f"{variant}.vst3" / "Contents" / "x86_64-linux" / f"{variant}.so"


def digest_file(path: Path) -> str:
    """Hash the just-built file while refusing symlinks and missing outputs."""
    if path.is_symlink() or not path.is_file():
        raise CaptureError(f"freshly built plugin binary is absent or symlinked: {path}")
    try:
        with path.open("rb") as stream:
            info = os.fstat(stream.fileno())
            if not stat.S_ISREG(info.st_mode) or not 0 < info.st_size <= 512 * 1024 * 1024:
                raise CaptureError("freshly built plugin binary is empty or oversized")
            digest = hashlib.sha256()
            for chunk in iter(lambda: stream.read(1024 * 1024), b""):
                digest.update(chunk)
    except OSError as exc:
        raise CaptureError(f"cannot hash freshly built plugin binary: {exc}") from exc
    return digest.hexdigest()


def verify_ci(manifest_path: Path, source_sha: str, bin_dir: Path, lv2_dir: Path) -> dict:
    if not manifest_path.is_file() or manifest_path.is_symlink() or manifest_path.stat().st_size > MAX_MANIFEST:
        raise CaptureError("missing, symlinked or oversized host-capture manifest; a real host recording is REQUIRED")
    try:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"), object_pairs_hook=_unique)
    except (json.JSONDecodeError, UnicodeError, RecursionError) as exc:
        raise CaptureError(f"invalid host-capture manifest: {exc}") from exc
    # Verify the complete bounded evidence package first. This also checks
    # source_sha and verifies the claimed plugin bytes against the manifest.
    result = verify(manifest, manifest_path.parent.resolve(), source_sha)
    actual = built_plugin_path(manifest["host"]["plugin_format"], manifest["mode"], bin_dir, lv2_dir)
    claimed_hash = manifest["plugin"]["sha256"]
    compiled_hash = digest_file(actual)
    if compiled_hash != claimed_hash:
        raise CaptureError("host-capture plugin hash differs from freshly built CI plugin binary")
    result["build_artifact_sha256"] = compiled_hash
    result["build_artifact_path"] = str(actual)
    result["provenance_scope_warning"] = (
        "The claimed plugin bytes match this CI build; recording origin and actual DAW hosting "
        "remain operator-attested, not independently established. No DAW WAV was generated by this script."
    )
    return result


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument("--expected-sha", required=True)
    parser.add_argument("--bin-dir", type=Path, default=Path("bin"))
    parser.add_argument("--lv2-dir", type=Path, default=Path("/tmp/lv2-path"))
    args = parser.parse_args(argv)
    try:
        result = verify_ci(args.manifest, args.expected_sha, args.bin_dir, args.lv2_dir)
    except (OSError, CaptureError) as exc:
        result = {"accepted": False, "error": str(exc)}
    print(json.dumps(result, indent=2, sort_keys=True))
    return 0 if result["accepted"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
