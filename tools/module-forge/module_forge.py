EFFECT_CORE_TEMPLATE = r'''// Generated by Module Forge; original first-party DSP starter (review adaptations).
// SPDX-License-Identifier: GPL-3.0-or-later
// Rack-independent TPT one-pole low-pass core for standalone DSP testing.
#pragma once

#include <algorithm>
#include <cmath>
#include <cstdint>
#include <cstring>

namespace moduleforge {

struct MS@@SLUG@@OnePole {
    float state = 0.f;

    // C++17 IEEE-754 binary32 guard. std::isfinite may be folded to true
    // by production -ffast-math; inspect exponent bits through memcpy instead.
    static bool finite(float value) noexcept {
        static_assert(sizeof(float) == sizeof(std::uint32_t),
                      "Module Forge requires IEEE-754 binary32 floats");
        std::uint32_t bits = 0;
        std::memcpy(&bits, &value, sizeof(bits));
        return (bits & 0x7f800000u) != 0x7f800000u;
    }

    void reset() noexcept {
        state = 0.f;
    }

    // Recalculate for the host sample rate; cutoff is constrained below Nyquist.
    static float coefficient(float cutoffHz, float sampleRate) noexcept {
        const float sr = (finite(sampleRate) && sampleRate >= 1000.f)
            ? sampleRate : 48000.f;
        const float cutoff = std::clamp(
            finite(cutoffHz) ? cutoffHz : 1000.f,
            5.f, 0.45f * sr);
        constexpr float kPi = 3.14159265358979323846f;
        const float g = std::tan(kPi * cutoff / sr);
        return g / (1.f + g);
    }

    float process(float input, float coefficient) noexcept {
        if (!finite(input))
            input = 0.f;
        input = std::clamp(input, -100.f, 100.f);
        if (!finite(coefficient))
            coefficient = 0.f;
        const float c = std::clamp(coefficient, 0.f, 1.f);
        const float v = (input - state) * c;
        const float output = state + v;
        state = output + v;
        if (!finite(output) || !finite(state)) {
            reset();
            return 0.f;
        }
        if (std::fabs(state) < 1e-20f)
            state = 0.f;
        return output;
    }
};

} // namespace moduleforge
'''

