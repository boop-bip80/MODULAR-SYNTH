INTEGRATION_TEMPLATE = '''# Integrating @@SLUG@@ into the ModularSynth collection

Generated outputs are a reviewed starting point, not automatically installed modules.
This workflow keeps the current self-contained Cardinal/ModularSynth architecture.

1. Copy `@@SLUG@@.cpp` to `plugins/ModularSynth/src/@@SLUG@@.cpp`.
2. Copy `@@SLUG@@.svg` to `plugins/ModularSynth/res/@@SLUG@@.svg`.
3. Add `PLUGIN_FILES += ModularSynth/src/@@SLUG@@.cpp` to the `ModularSynth`
   sources in `plugins/Makefile`. Preserve the current
   `-DpluginInstance=pluginInstance__ModularSynth` compilation setup.
4. Add `extern Model* modelMS@@SLUG@@;` in
   `plugins/ModularSynth/src/plugin.hpp`.
5. Add `p->addModel(modelMS@@SLUG@@);` inside `initStatic__ModularSynth()`
   in `plugins/plugins.cpp` (not in `initStatic__Cardinal`).
6. Insert the object from `@@SLUG@@.module.json` into the existing
   `modules` array in `plugins/ModularSynth/plugin.json`.
   Do not replace that manifest with this single-module fragment.
7. Build the affected Cardinal variants and run their self-tests and host
   validation, then audition 1 V/oct tracking, sample-rate changes, and
   polyphonic output before merging.

Cardinal Mini needs its own reviewed registration and
`MINIPLUGIN_FILES` change and is NOT included by default.

The starter emits a 5 V peak sine and limits its frequency below Nyquist.
Replace its DSP with an original algorithm while preserving real-time
constraints: no allocation, locks, file access, or blocking IO in process().

Module slugs, model names, and panel paths are stable patch identifiers.
Changing them later can break existing patches. Respect GPL-compatible
licensing, original artwork rights, and upstream attribution.
'''

def validate_slug(slug: str) -> None:
    if not SLUG_PATTERN.fullmatch(slug):
        raise ValueError("slug must be 2-40 ASCII alphanumerics, start with A-Z")

def validate_name(name: str) -> None:
    if not NAME_PATTERN.fullmatch(name):
        raise ValueError("name must be 1-64 ASCII letters, digits, spaces, _ or -")

def manifest_for(slug: str, name: str) -> dict:
    return {
        "slug": slug,
        "name": name,
        "description": "Original Module Forge sine oscillator starter",
        "tags": ["Oscillator", "Polyphonic"],
    }

def render_files(slug: str, name: str) -> dict[str, str]:
    validate_slug(slug)
    validate_name(name)
    cpp = SOURCE_TEMPLATE.replace("@@SLUG@@", slug)
    svg = PANEL_TEMPLATE.replace("@@TITLE@@", escape(name))
    docs = INTEGRATION_TEMPLATE.replace("@@SLUG@@", slug)
    manifest = json.dumps(manifest_for(slug, name), indent=2) + "\n"
    return {
        f"{slug}.cpp": cpp,
        f"{slug}.svg": svg,
        f"{slug}.module.json": manifest,
        "INTEGRATION.md": docs,
    }

def generate(slug: str, name: str, output_root: Path) -> Path:
    files = render_files(slug, name)
    destination = output_root / slug
    # Never modify previously generated or manually edited modules.
    destination.mkdir(parents=True, exist_ok=False)
    for filename, contents in files.items():
        (destination / filename).write_text(contents, encoding="utf-8")
    return destination

def check_module(path: Path) -> list[str]:
    errors: list[str] = []
    slug = path.name
    try:
        validate_slug(slug)
    except ValueError as exc:
        return [str(exc)]
    expected = (f"{slug}.cpp", f"{slug}.svg",
                f"{slug}.module.json", "INTEGRATION.md")
    for filename in expected:
        if not (path / filename).is_file():
            errors.append(f"missing {filename}")
    if errors:
        return errors
    try:
        manifest = json.loads((path / f"{slug}.module.json").read_text(encoding="utf-8"))
        if manifest.get("slug") != slug:
            errors.append("manifest slug does not match directory")
        validate_name(manifest.get("name", ""))
        source = (path / f"{slug}.cpp").read_text(encoding="utf-8")
        if f'createModel<MS{slug}Module, MS{slug}Widget>("{slug}")' not in source:
            errors.append("source model registration does not match manifest")
        if f'"res/{slug}.svg"' not in source:
            errors.append("source panel path does not match generated SVG")
        from xml.etree import ElementTree
        ElementTree.parse(path / f"{slug}.svg")
    except (OSError, ValueError, TypeError) as exc:
        errors.append(f"invalid generated module: {exc}")
    return errors

def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    subparsers = parser.add_subparsers(dest="command", required=True)
    new = subparsers.add_parser("new", help="create a new module skeleton")
    new.add_argument("--slug", required=True, help="stable PascalCase module ID")
    new.add_argument("--name", required=True, help="human-readable module name")
    new.add_argument("--out", type=Path, default=Path("module-forge-output"),
                     help="parent directory for generated module folder")
    check = subparsers.add_parser("check", help="validate a generated skeleton")
    check.add_argument("path", type=Path, help="path to generated module folder")
    args = parser.parse_args(argv)
    try:
        if args.command == "new":
            destination = generate(args.slug, args.name, args.out)
            print(f"Generated {destination}")
            print(f"Read {destination / 'INTEGRATION.md'} before integrating.")
            return 0
        errors = check_module(args.path)
        for error in errors:
            print(error, file=sys.stderr)
        if errors:
            return 1
        print(f"Valid skeleton: {args.path}")
        return 0
    except (ValueError, OSError) as exc:
        print(f"Module Forge: {exc}", file=sys.stderr)
        return 2

if __name__ == "__main__":
    raise SystemExit(main())
