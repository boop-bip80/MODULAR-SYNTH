SAW_BLEP_HELPER = r'''    // Polynomial BLEP smooths the saw reset over one sample.
    // dt is bounded to (0, 0.45] by the inherited frequency clamp.
    static float polyBlep(float t, float dt) noexcept {
        if (t < dt) {
            const float u = t / dt;
            return u + u - u * u - 1.f;
        }
        if (t > 1.f - dt) {
            const float u = (t - 1.f) / dt;
            return u * u + u + u + 1.f;
        }
        return 0.f;
    }

'''
