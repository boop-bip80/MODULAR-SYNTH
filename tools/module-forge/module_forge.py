#!/usr/bin/env python3
"""Generate and validate a first-party Cardinal/Rack module skeleton.

No third-party dependencies. This tool does not modify Cardinal's build files:
review the generated integration instructions before wiring the module in.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path
from xml.sax.saxutils import escape

SLUG_PATTERN = re.compile(r"[A-Z][A-Za-z0-9]{1,39}\Z")
NAME_PATTERN = re.compile(r"[A-Za-z0-9][A-Za-z0-9 _-]{0,63}\Z")

SOURCE_TEMPLATE = r'''// Generated by Module Forge. GPL-3.0-or-later.
// A conservative 16-channel sine oscillator starter, not a finished flagship DSP engine.
#include "plugin.hpp"

#include <algorithm>
#include <array>
#include <cmath>

struct MS@@SLUG@@Module final : Module {
    enum ParamIds { COARSE_PARAM, NUM_PARAMS };
    enum InputIds { PITCH_INPUT, NUM_INPUTS };
    enum OutputIds { AUDIO_OUTPUT, NUM_OUTPUTS };
    enum LightIds { NUM_LIGHTS };

    static constexpr int kMaxChannels = 16;
    std::array<float, kMaxChannels> phase{};

    MS@@SLUG@@Module() {
        config(NUM_PARAMS, NUM_INPUTS, NUM_OUTPUTS, NUM_LIGHTS);
        configParam(COARSE_PARAM, -4.f, 4.f, 0.f, "Coarse frequency", " oct");
        configInput(PITCH_INPUT, "1 V/oct pitch");
        configOutput(AUDIO_OUTPUT, "Sine audio");
    }

    void onReset() override {
        phase.fill(0.f);
    }

    void process(const ProcessArgs& args) override {
        const int voices = std::min(kMaxChannels,
            std::max(1, inputs[PITCH_INPUT].getChannels()));
        outputs[AUDIO_OUTPUT].setChannels(voices);

        for (int voice = 0; voice < voices; ++voice) {
            float pitch = params[COARSE_PARAM].getValue()
                + inputs[PITCH_INPUT].getPolyVoltage(voice);
            if (!std::isfinite(pitch))
                pitch = 0.f;
            pitch = std::clamp(pitch, -8.f, 8.f);

            const float sampleRate = std::max(1.f, args.sampleRate);
            const float frequency = std::min(
                261.625565f * std::exp2(pitch), sampleRate * 0.45f);
            phase[voice] += frequency / sampleRate;
            if (phase[voice] >= 1.f)
                phase[voice] -= 1.f;

            outputs[AUDIO_OUTPUT].setVoltage(
                5.f * std::sin(6.28318530718f * phase[voice]), voice);
        }
    }
};

#ifndef HEADLESS
struct MS@@SLUG@@Widget final : ModuleWidget {
    explicit MS@@SLUG@@Widget(MS@@SLUG@@Module* module) {
        setModule(module);
        setPanel(APP->window->loadSvg(
            asset::plugin(pluginInstance, "res/@@SLUG@@.svg")));
        addParam(createParamCentered<RoundBlackKnob>(
            mm2px(Vec(25.4f, 36.f)), module, MS@@SLUG@@Module::COARSE_PARAM));
        addInput(createInputCentered<PJ301MPort>(
            mm2px(Vec(25.4f, 70.f)), module, MS@@SLUG@@Module::PITCH_INPUT));
        addOutput(createOutputCentered<PJ301MPort>(
            mm2px(Vec(25.4f, 100.f)), module, MS@@SLUG@@Module::AUDIO_OUTPUT));
    }
};
#else
struct MS@@SLUG@@Widget final : ModuleWidget {
    explicit MS@@SLUG@@Widget(MS@@SLUG@@Module* module) {
        setModule(module);
        addParam(createParam<RoundBlackKnob>(
            {}, module, MS@@SLUG@@Module::COARSE_PARAM));
        addInput(createInput<PJ301MPort>(
            {}, module, MS@@SLUG@@Module::PITCH_INPUT));
        addOutput(createOutput<PJ301MPort>(
            {}, module, MS@@SLUG@@Module::AUDIO_OUTPUT));
    }
};
#endif

Model* modelMS@@SLUG@@ =
    createModel<MS@@SLUG@@Module, MS@@SLUG@@Widget>("@@SLUG@@");
'''

