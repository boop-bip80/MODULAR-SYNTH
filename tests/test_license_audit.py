"""Source-only attribution and license-notice preflight regression tests."""
from __future__ import annotations

import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from tools.compliance.license_audit import audit_repository  # noqa: E402

LICENSE = "GPL-3.0-or-later"
FORK = "https://github.com/boop-bip80/MODULAR-SYNTH"


def write(root: Path, relative: str, content: str) -> None:
    file = root / relative
    file.parent.mkdir(parents=True, exist_ok=True)
    file.write_text(content, encoding="utf-8")


def manifest(models: list[str] | None = None, *, license_name: str = LICENSE,
             source: str = FORK) -> str:
    return json.dumps({
        "slug": "ModularSynth",
        "name": "MODULAR-SYNTH Originals",
        "license": license_name,
        "author": "boop-bip80 contributors",
        "authorUrl": "https://github.com/boop-bip80",
        "sourceUrl": source,
        "pluginUrl": FORK,
        "modules": [{"slug": slug, "name": slug} for slug in (models or ["MorphVCO", "Macro8"])],
    }, indent=2) + "\n"


def cpp() -> str:
    return (
        "/* Original MODULAR-SYNTH first-party module\n"
        " * Copyright (C) 2026 boop-bip80 contributors\n"
        " * SPDX-License-Identifier: GPL-3.0-or-later\n"
        " */\n"
        "int test_module = 0;\n"
    )


def svg() -> str:
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Original MODULAR-SYNTH first-party panel -->\n'
        '<svg xmlns="http://www.w3.org/2000/svg"><rect width="10" height="10"/></svg>\n'
    )


def forge_templates() -> str:
    """Real names and notice styles, but inert template literals only."""
    return (
        'SOURCE_TEMPLATE = "// Generated by Module Forge. GPL-3.0-or-later.\\n"\n'
        'PANEL_TEMPLATE = "<svg></svg>"\n'
        'INTEGRATION_TEMPLATE = "Review license and upstream attribution before integration."\n'
        'EFFECT_SOURCE_TEMPLATE = "// Generated by Module Forge. GPL-3.0-or-later.\\n"\n'
        'EFFECT_CORE_TEMPLATE = "// Generated by Module Forge. GPL-3.0-or-later.\\n"\n'
        'EFFECT_PANEL_TEMPLATE = "<svg></svg>"\n'
        'EFFECT_INTEGRATION_TEMPLATE = "Integrate first-party source after review."\n'
    )


def fixture(root: Path) -> None:
    write(root, "plugins/ModularSynth/plugin.json", manifest())
    for slug in ("MorphVCO", "Macro8"):
        write(root, f"plugins/ModularSynth/src/{slug}.cpp", cpp())
        write(root, f"plugins/ModularSynth/res/{slug}.svg", svg())
    write(root, "plugins/ModularSynth/src/plugin.hpp", cpp())
    write(root, "tools/module-forge/module_forge.py", forge_templates())
    write(root, "LICENSE", "GNU GENERAL PUBLIC LICENSE\nVersion 3, 29 June 2007\n")
    write(root, "docs/LICENSES.md", "Cardinal license inventory includes Rack and DPF.\n")
    write(root, "docs/LICENSE-PERMISSIONS.md", "# LICENSE PERMISSIONS\n")
    write(root, "docs/MODULE_FORGE.md", "Review each license and upstream attribution.\n")
    write(root, "README.md", "Derived from DISTRHO/Cardinal, VCV Rack and DPF.\n")
    write(root, ".gitmodules", (
        '[submodule "rack"]\n'
        '\tpath = src/Rack\n'
        '\turl = https://github.com/VCVRack/Rack.git\n'
        '[submodule "dpf"]\n'
        '\tpath = dpf\n'
        '\turl = https://github.com/DISTRHO/DPF.git\n'
        '[submodule "plugin"]\n'
        '\tpath = plugins/Other\n'
        '\turl = https://github.com/example/Other.git\n'
    ))


def codes(report: dict, *, level: str | None = None) -> set[str]:
    return {
        item["code"] for item in report["findings"]
        if level is None or item["level"] == level
    }


class LicenseAuditTests(unittest.TestCase):
    def setUp(self) -> None:
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.repo = Path(self.temp.name)
        fixture(self.repo)

    def test_baseline_passes_hard_checks_and_reports_advisory_gaps(self) -> None:
        report = audit_repository(self.repo)
        self.assertEqual(report["summary"]["errors"], 0, report["findings"])
        self.assertTrue(report["summary"]["passed"])
        self.assertEqual(report["summary"]["first_party_models"], 2)
        self.assertEqual(report["summary"]["first_party_cpp_files"], 3)
        self.assertEqual(report["summary"]["first_party_svg_panels"], 2)
        self.assertEqual(report["summary"]["upstream_submodule_pointers"], 3)
        self.assertEqual(report["summary"]["warnings"], 8)
        self.assertIn("forge_panel_notice", codes(report, level="warning"))
        self.assertIn("missing_spdx", codes(report, level="warning"))
        self.assertNotIn("inconsistent_spdx", codes(report))

    def test_strict_promotes_warnings_without_relabeling_them(self) -> None:
        normal = audit_repository(self.repo)
        strict = audit_repository(self.repo, strict=True)
        self.assertEqual(strict["summary"]["errors"], normal["summary"]["errors"])
        self.assertEqual(strict["summary"]["warnings"], normal["summary"]["warnings"])
        self.assertTrue(normal["summary"]["passed"])
        self.assertFalse(strict["summary"]["passed"])

    def test_cpp_missing_or_conflicting_license_or_copyright_is_error(self) -> None:
        path = "plugins/ModularSynth/src/MorphVCO.cpp"
        source = cpp()
        for replacement, code in (
            (source.replace("SPDX-License-Identifier", "License"), "missing_spdx"),
            (source.replace(LICENSE, "MIT"), "inconsistent_spdx"),
            (source.replace("Copyright (C)", "Authored"), "missing_copyright"),
        ):
            with self.subTest(code=code):
                write(self.repo, path, replacement)
                report = audit_repository(self.repo)
                self.assertIn(code, codes(report, level="error"))
                self.assertFalse(report["summary"]["passed"])
        write(self.repo, path, source)
        self.assertEqual(audit_repository(self.repo)["summary"]["errors"], 0)

    def test_panel_requires_original_marker_and_flags_conflicting_spdx(self) -> None:
        path = "plugins/ModularSynth/res/Macro8.svg"
        write(self.repo, path, svg().replace("Original MODULAR-SYNTH", "Copied graphic"))
        self.assertIn("missing_panel_origin", codes(audit_repository(self.repo), level="error"))
        write(self.repo, path, svg().replace(
            "<!-- Original MODULAR-SYNTH first-party panel -->",
            "<!-- Original MODULAR-SYNTH first-party panel; SPDX-License-Identifier: MIT -->",
        ))
        self.assertIn("inconsistent_spdx", codes(audit_repository(self.repo), level="error"))

    def test_matching_svg_spdx_removes_only_its_advisory(self) -> None:
        before = audit_repository(self.repo)
        path = "plugins/ModularSynth/res/Macro8.svg"
        content = svg().replace(
            "<!-- Original MODULAR-SYNTH first-party panel -->",
            f"<!-- Original MODULAR-SYNTH first-party panel; SPDX-License-Identifier: {LICENSE} -->",
        )
        write(self.repo, path, content)
        after = audit_repository(self.repo)
        self.assertEqual(after["summary"]["warnings"], before["summary"]["warnings"] - 1)
        self.assertEqual(after["summary"]["errors"], 0)

    def test_manifest_license_identity_duplicate_and_missing_asset(self) -> None:
        path = "plugins/ModularSynth/plugin.json"
        write(self.repo, path, '{"slug":"ModularSynth","slug":"Other","modules":[]}')
        self.assertIn("manifest_json", codes(audit_repository(self.repo), level="error"))
        write(self.repo, path, manifest(license_name="MIT"))
        self.assertIn("manifest_license", codes(audit_repository(self.repo), level="error"))
        write(self.repo, path, manifest(source="https://github.com/DISTRHO/Cardinal"))
        self.assertIn("source_url", codes(audit_repository(self.repo), level="error"))
        write(self.repo, path, manifest(models=["MorphVCO", "MorphVCO"]))
        self.assertIn("duplicate_model", codes(audit_repository(self.repo), level="error"))
        write(self.repo, path, manifest(models=["MorphVCO", "Macro8", "AnotherNewModel"]))
        self.assertIn("model_asset_missing", codes(audit_repository(self.repo), level="error"))

    def test_generator_source_template_license_and_required_templates(self) -> None:
        path = "tools/module-forge/module_forge.py"
        write(self.repo, path, forge_templates().replace(
            "GPL-3.0-or-later", "license pending", 1,
        ))
        self.assertIn("forge_license", codes(audit_repository(self.repo), level="error"))
        write(self.repo, path, forge_templates().replace(
            'EFFECT_CORE_TEMPLATE = "// Generated by Module Forge. GPL-3.0-or-later.\\n"\n',
            "",
        ))
        self.assertIn("forge_template_missing", codes(audit_repository(self.repo), level="error"))

    def test_attribution_and_upstream_pointers_are_required_but_not_scanned(self) -> None:
        write(self.repo, "docs/LICENSES.md", "unrelated text")
        self.assertIn("attribution_pointer", codes(audit_repository(self.repo), level="error"))
        write(self.repo, "docs/LICENSES.md", "Cardinal license inventory includes Rack and DPF.")
        write(self.repo, ".gitmodules", (
            '[submodule "rack"]\n'
            'path = src/Rack\nurl = https://github.com/VCVRack/Rack.git\n'
        ))
        report = audit_repository(self.repo)
        self.assertIn("upstream_pointer", codes(report, level="error"))
        self.assertIn("thirdparty_pointer", codes(report, level="error"))
        self.assertFalse(any(item["path"].startswith("plugins/Other/")
                             for item in report["findings"]))

    def test_unrelated_inherited_source_without_notice_is_never_rejected(self) -> None:
        write(self.repo, "plugins/Other/Legacy.cpp", "int old_code = 1;\n")
        before = audit_repository(self.repo)
        write(self.repo, "src/Rack/no-license.cpp", "int inherited = 1;\n")
        after = audit_repository(self.repo)
        self.assertEqual(before, after)
        self.assertTrue(after["summary"]["passed"])

    def test_deterministic_json_and_cli_exit_codes(self) -> None:
        script = ROOT / "tools" / "compliance" / "license_audit.py"

        def call(*args: str) -> subprocess.CompletedProcess[str]:
            return subprocess.run(
                [sys.executable, str(script), "--repo-root", str(self.repo), *args],
                cwd=ROOT, text=True, capture_output=True, check=False,
            )

        first = call("--json")
        self.assertEqual(first.returncode, 0, first.stderr)
        self.assertEqual(first.stdout, call("--json").stdout)
        parsed = json.loads(first.stdout)
        self.assertTrue(parsed["summary"]["passed"])
        self.assertEqual(parsed["findings"], audit_repository(self.repo)["findings"])
        strict = call("--strict")
        self.assertEqual(strict.returncode, 1)
        self.assertIn("FAIL", strict.stdout)
        write(self.repo, "plugins/ModularSynth/src/MorphVCO.cpp", "int unlicensed = 1;\n")
        broken = call()
        self.assertEqual(broken.returncode, 1)
        self.assertIn("missing_spdx", broken.stdout)
        missing = subprocess.run(
            [sys.executable, str(script), "--repo-root", str(self.repo / "missing")],
            cwd=ROOT, text=True, capture_output=True, check=False,
        )
        self.assertEqual(missing.returncode, 2)

    def test_actual_checkout_has_no_first_party_hard_notice_errors(self) -> None:
        actual = Path(os.environ.get("MODULAR_SYNTH_AUDIT_CHECKOUT", str(ROOT)))
        if not (actual / "plugins" / "ModularSynth" / "plugin.json").is_file():
            self.skipTest("full source checkout not present in temporary test workspace")
        report = audit_repository(actual)
        self.assertEqual(report["summary"]["errors"], 0, report["findings"])
        self.assertGreaterEqual(report["summary"]["first_party_models"], 3)
        self.assertGreaterEqual(report["summary"]["upstream_submodule_pointers"], 3)


if __name__ == "__main__":
    unittest.main()
